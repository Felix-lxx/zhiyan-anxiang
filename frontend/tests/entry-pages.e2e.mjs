// Real login/read/navigation; mutation failure tests are intercepted, never written to user data.
// QA_PASSWORD required. Optional: QA_BASE_URL, QA_USERNAME, PLAYWRIGHT_MODULE,
// QA_BROWSER_PATH, QA_ARTIFACT_DIR. Run with a Playwright installation available.
import assert from 'node:assert/strict'
import { mkdirSync } from 'node:fs'
import { resolve } from 'node:path'
const { default: playwright } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
assert.ok(process.env.QA_PASSWORD, 'Set QA_PASSWORD for a local test account')
const base = process.env.QA_BASE_URL || 'http://127.0.0.1:5173'
const artifacts = resolve(process.env.QA_ARTIFACT_DIR || '.tmp/entry-review')
mkdirSync(artifacts, { recursive: true })
const browser = await playwright.chromium.launch({ headless: true, ...(process.env.QA_BROWSER_PATH ? { executablePath: process.env.QA_BROWSER_PATH } : {}) })
const results = []
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, reducedMotion: 'reduce' })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.setDefaultTimeout(15_000)
  const noOverflow = async (surface, width) => {
    const overflowing = await page.evaluate(() => [...document.querySelectorAll('main button, main input, main select, main h1, main h2, main h3')].filter(el => {
      const r = el.getBoundingClientRect()
      return r.width && r.height && (r.left < -1 || r.right > innerWidth + 1 || el.scrollWidth > el.clientWidth + 2)
    }).map(el => ({ tag: el.tagName, text: el.textContent?.trim(), className: el.className })))
    assert.deepEqual(overflowing, [], `${surface} ${width}px: controls/text stay in bounds`)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
  }
  const homeReady = async () => {
    await page.waitForURL('**/projects')
    await page.locator('.home-list-summary').waitFor()
  }
  await page.goto(`${base}/login`)
  await page.getByText('服务已就绪', { exact: true }).waitFor()
  await page.waitForFunction(() => document.querySelector('.entry-scene img')?.naturalWidth > 0)
  await page.keyboard.press('Tab')
  assert.equal(await page.locator('#username').evaluate(el => el === document.activeElement), true, 'keyboard starts with login, not photo credit')
  for (const width of [320, 390, 768, 1024, 1440, 1920]) {
    await page.setViewportSize({ width, height: width < 700 ? 844 : 960 })
    await noOverflow('login', width)
    if ([390, 1440].includes(width)) await page.screenshot({ path: `${artifacts}/login-${width}.png`, fullPage: true })
  }
  await page.setViewportSize({ width: 1440, height: 960 })
  await page.locator('#username').fill(process.env.QA_USERNAME || 'admin')
  await page.locator('#password').fill(process.env.QA_PASSWORD)
  await page.getByRole('button', { name: '显示密码' }).click()
  assert.equal(await page.locator('#password').getAttribute('type'), 'text')
  await page.getByRole('button', { name: '隐藏密码' }).click()
  const authFailure = route => route.fulfill({ status: 401, contentType: 'application/json', body: JSON.stringify({ detail: '测试：账号或密码不正确' }) })
  await page.route('**/api/v1/auth/login', authFailure)
  await page.getByRole('button', { name: '登录演练工作台' }).click()
  await page.getByRole('alert').filter({ hasText: '账号或密码不正确' }).waitFor()
  await page.unroute('**/api/v1/auth/login', authFailure)
  await page.getByRole('button', { name: '登录演练工作台' }).click()
  await homeReady()
  results.push('real login, password visibility, injected login failure recovery, keyboard order')
  const count = await page.locator('.home-project-row').count()
  assert.ok(count > 0, 'test environment contains at least one community')
  assert.equal(await page.locator('.home-header [aria-current="page"]').count(), 1)
  for (const width of [320, 390, 768, 1024, 1440, 1920]) {
    await page.setViewportSize({ width, height: width < 700 ? 844 : 960 })
    await noOverflow('home', width)
    if ([390, 1440, 1920].includes(width)) await page.screenshot({ path: `${artifacts}/home-${width}.png`, fullPage: true })
  }
  results.push('login/home bounds at 320, 390, 768, 1024, 1440, 1920px; settled desktop/mobile screenshots')
  await page.setViewportSize({ width: 1440, height: 960 })
  await page.getByRole('button', { name: '示例训练', exact: true }).click()
  await page.waitForURL('**/projects?section=training')
  assert.equal(await page.locator('.home-header [aria-current="page"]').count(), 1)
  await page.waitForFunction(() => document.querySelector('.home-feature__scene img')?.naturalWidth > 0)
  await noOverflow('desktop training view', 1440)
  await page.screenshot({ path: `${artifacts}/home-training-1440.png`, fullPage: true })
  await page.getByRole('button', { name: '使用说明', exact: true }).click()
  await page.waitForURL('**/projects?section=guide')
  assert.equal(await page.locator('.home-header [aria-current="page"]').count(), 1)
  await noOverflow('desktop guide view', 1440)
  await page.screenshot({ path: `${artifacts}/home-guide-1440.png`, fullPage: true })
  await page.getByRole('button', { name: /^社区项目/ }).click()
  await homeReady()
  await page.setViewportSize({ width: 1440, height: 720 })
  await page.evaluate(() => scrollTo(0, document.documentElement.scrollHeight))
  const rail = await page.locator('.home-header').boundingBox()
  assert.ok(rail && Math.abs(rail.y) <= 1 && Math.abs(rail.height - 720) <= 1, `desktop sidebar remains fitted to viewport while page scrolls: ${JSON.stringify(rail)}`)
  await page.getByRole('button', { name: '打开个人中心' }).click()
  await page.waitForURL('**/projects?section=account')
  assert.equal(await page.getByRole('heading', { name: '个人中心', level: 1 }).evaluate(el => el === document.activeElement), true)
  assert.equal(await page.locator('#home-account-panel').count(), 0)
  assert.equal(await page.locator('.home-header [aria-current="page"]').count(), 1)
  await noOverflow('desktop account view', 1440)
  await page.screenshot({ path: `${artifacts}/home-account-1440.png`, fullPage: false })
  await page.goBack()
  await homeReady()
  results.push('desktop sidebar remains viewport-bound while scrolling; personal center is a routed view without overlay')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('searchbox', { name: '搜索社区项目' }).fill('不存在的社区-QA')
  await page.getByText('没有找到符合条件的社区', { exact: true }).waitFor()
  await page.getByRole('button', { name: '清除筛选' }).click()
  assert.equal(await page.locator('.home-project-row').count(), count)
  await page.getByLabel('项目状态').selectOption('archived')
  assert.equal(await page.locator('.home-project-row .home-status:not([data-status="archived"])').count(), 0)
  await page.getByLabel('项目状态').selectOption('all')
  await page.getByRole('button', { name: '使用说明', exact: true }).click()
  await page.waitForURL('**/projects?section=guide')
  assert.equal(await page.getByRole('heading', { name: '使用说明', level: 1 }).evaluate(el => el === document.activeElement), true)
  await noOverflow('mobile guide view', 390)
  await page.screenshot({ path: `${artifacts}/home-guide-390.png`, fullPage: true })
  await page.getByRole('button', { name: '打开个人中心' }).click()
  await page.waitForURL('**/projects?section=account')
  assert.equal(await page.locator('#home-account-panel').count(), 0)
  await noOverflow('mobile account view', 390)
  await page.getByRole('button', { name: /^社区项目/ }).click()
  await homeReady()
  await page.getByRole('button', { name: '新建社区项目', exact: true }).click()
  assert.equal(await page.locator('#community-name').evaluate(el => el === document.activeElement), true)
  await page.locator('#community-name').fill('布局验收项目（不写入数据库）')
  await page.locator('#community-address').fill('表单失败后应保留此地址')
  const createFailure = route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: '测试：保存暂不可用，请重试' }) })
  await page.route('**/api/v1/communities', createFailure)
  await page.getByRole('button', { name: '创建社区项目', exact: true }).click()
  await page.getByRole('alert').filter({ hasText: '保存暂不可用' }).waitFor()
  assert.equal(await page.locator('#community-address').inputValue(), '表单失败后应保留此地址')
  await noOverflow('mobile create/error', 390)
  await page.unroute('**/api/v1/communities', createFailure)
  await page.getByRole('button', { name: '暂不创建' }).click()
  assert.equal(await page.locator('#new-community-trigger').evaluate(el => el === document.activeElement), true)
  results.push('mobile search/status filter, routed guide/focus, routed personal center, create form focus/error/input retention/cancel')
  const demoFailure = route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: '测试：案例暂不可用，请重试' }) })
  await page.route('**/api/v1/communities/demo-ready', demoFailure)
  await page.getByRole('button', { name: '示例训练', exact: true }).click()
  await page.waitForURL('**/projects?section=training')
  await page.waitForFunction(() => document.querySelector('.home-feature__scene img')?.naturalWidth > 0)
  await noOverflow('mobile training view', 390)
  await page.screenshot({ path: `${artifacts}/home-training-390.png`, fullPage: true })
  await page.getByRole('button', { name: '立即进入三维演练', exact: true }).click()
  await page.getByRole('alert').filter({ hasText: '案例暂不可用' }).waitFor()
  assert.equal(await page.getByRole('button', { name: '立即进入三维演练', exact: true }).isEnabled(), true)
  await page.unroute('**/api/v1/communities/demo-ready', demoFailure)
  await page.getByRole('button', { name: /^社区项目/ }).click()
  await homeReady()
  await page.getByRole('button', { name: '编辑地图', exact: true }).first().click()
  await page.waitForURL('**/map')
  await page.goto(`${base}/projects`)
  await homeReady()
  assert.equal(await page.locator('.home-project-row').count(), count)
  await page.getByRole('button', { name: '演练中心', exact: true }).first().click()
  await page.waitForURL('**/operations')
  await page.goto(`${base}/projects`)
  await homeReady()
  results.push('demo failure/retry affordance, real map/operations route navigation, authenticated refresh')
  await page.getByRole('button', { name: '打开个人中心' }).click()
  await page.waitForURL('**/projects?section=account')
  await page.getByRole('button', { name: '退出登录' }).click()
  await page.waitForURL('**/login')
  assert.equal(await page.evaluate(() => localStorage.getItem('zhiyan_access_token')), null)
  const healthFailure = route => route.abort('failed')
  await page.route('**/api/v1/health', healthFailure)
  await page.getByRole('button', { name: '重新检查' }).click()
  await page.getByText('服务暂不可达', { exact: true }).waitFor()
  assert.equal(await page.getByRole('button', { name: '登录演练工作台' }).isDisabled(), true)
  await noOverflow('mobile offline', 390)
  await page.unroute('**/api/v1/health', healthFailure)
  await page.getByRole('button', { name: '重新检查' }).click()
  await page.getByText('服务已就绪', { exact: true }).waitFor()
  results.push('logout clears token; health failure disables login; recheck recovers')
  assert.deepEqual(errors, [], 'no uncaught browser errors')
  console.log(JSON.stringify({ status: 'PASS', checks: results, artifacts }, null, 2))
} finally { await browser.close() }
