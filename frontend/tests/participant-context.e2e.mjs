 await page.locator('.participant-header strong').getByText(original.name,{exact:true}).waitFor()
 assert.equal(new URL(page.url()).searchParams.get('drill'),original.id)
 await page.getByRole('button',{name:'退出参演',exact:true}).click()
 await page.locator('.director-topbar').waitFor()
 if(await close.isVisible())await close.click()
