  assert.equal(await page.locator('.participant-header strong').innerText(),'智演安巷')
  await page.goto(local)
  await page.locator('.participant-header strong').getByText(original.name,{exact:true}).waitFor()
 await page.getByRole('button',{name:'退出参演',exact:true}).click()
