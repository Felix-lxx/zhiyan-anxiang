import assert from 'node:assert/strict'
import {mkdirSync,writeFileSync} from 'node:fs'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright')
assert.ok(process.env.QA_PASSWORD,'Use an isolated QA account and database')
const base=process.env.QA_BASE_URL,api=process.env.QA_API_URL
assert.ok(base&&api,'QA_BASE_URL and QA_API_URL must point to disposable QA services')
const out='../output/playwright/participant-context';mkdirSync(out,{recursive:true})
const browser=await chromium.launch({headless:true,...(process.env.QA_BROWSER_PATH?{executablePath:process.env.QA_BROWSER_PATH}:{})})
const context=await browser.newContext(),page=await context.newPage(),errors=[]
page.on('pageerror',e=>errors.push(e.message))
let headers={},root
